/* X레이 — 자당/타당 발의 법안 찬성률, **의원 한 명 = 한 행**
 *
 * 기존 getCrossPartyGapDist 는 두 값의 **차이**만 본다. 그래서 격차 2%p 가
 * `99→97` 인지 `70→68` 인지 구분하지 못한다. 이 쿼리는 그 수준을 보여준다.
 *
 * 🔴 **히스토그램(버킷 집계)으로 되돌리지 말 것.** 처음엔 2%p 폭 20구간으로 세어
 *    두 분포를 겹쳐 그렸는데 읽을 수 없는 그림이 나왔다 (2026-08-15 폐기):
 *      · 자당은 한 칸(98~100%)에 **244명(92%)** 이 몰려 y축을 독점한다.
 *        두 계열이 같은 높이 기준을 쓰므로 타당 분포(1~52명)가 전부 바닥에 눌려 모양이 사라졌다
 *      · 데이터가 오른쪽 25%에만 있어 화면 대부분이 빈 공간이었다
 *    → **높이를 아예 안 쓰는 점 그래프**로 바꿨다. 두 줄을 같은 x축에 놓고
 *      가로로 얼마나 퍼졌는지만 비교한다. 그게 이 섹션이 말하려는 전부다.
 *
 * ⚠️ 정렬은 화면의 세로 지터(겹침 분산)를 **결정적으로** 만들기 위한 것이다.
 *    정렬이 흔들리면 새로고침마다 점 위치가 바뀐다.
 * ⚠️ 266행이라 페이로드가 작다. 코호트가 커지면(자·타당 각 50표 조건 완화 등)
 *    점이 뭉개지므로 그때는 표본 추출이나 다른 표현을 고려할 것.
 * 대상: in_cohort — 격차 분포와 같은 모집단이라 숫자가 맞물린다
 */
SELECT own_rate::float8   AS own_rate
     , other_rate::float8 AS other_rate
  FROM politician_cross_party_vote
 WHERE in_cohort
 ORDER BY other_rate, own_rate, mona_cd
