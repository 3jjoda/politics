SELECT P.POLITICIAN_ID
     , P.PARTY_ID
     , P.PARTY_NAME
     , P.POLITICIAN_TYPE
     , FN_GET_CODE_NAME(P.POLITICIAN_TYPE) AS POLITICIAN_TYPE_NAME
     , P.NAME
     , P.ENG_NM
     , P.ELECTORAL_DISTRICT
     , P.PHOTO_URL
     , P.BIRTHDAY
     , P.REELE_GBN_NM
     , P.MONA_CD 
  FROM POLITICIANS P